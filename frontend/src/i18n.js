export function getAppLanguage() {
  return localStorage.getItem('finance-os-language') || 'en';
}

export function setAppLanguage(langCode) {
  const selected = SUPPORTED_LANGUAGES.find(l => l.code === langCode) || SUPPORTED_LANGUAGES[0];
  localStorage.setItem('finance-os-language', selected.code);
  
  // Set HTML direction for Arabic RTL support
  document.documentElement.setAttribute('dir', selected.dir);
  document.documentElement.setAttribute('lang', selected.code);
  
  window.dispatchEvent(new CustomEvent('languageChange', { detail: { language: selected.code, dir: selected.dir } }));
}

export function t(key, fallback = '') {
  const currentLang = getAppLanguage();
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || fallback || key;
}

