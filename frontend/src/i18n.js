export function getAppLanguage() {
  return localStorage.getItem('finance-os-language') || 'en';
}

export function setAppLanguage(langCode) {
  const selected = SUPPORTED_LANGUAGES.find(l => l.code === langCode) || SUPPORTED_LANGUAGES[0];
  localStorage.setItem('finance-os-language', selected.code);
  
  // Set HTML direction for Arabic RTL support
  document.documentElement.setAttribute('dir', selected.dir);
  document.documentElement.setAttribute('lang', selected.code);
  
  window.dispatchEvent(new CustomEvent('languageChange', { detail: { language: selected.code, dir: selected.dir } }));
}

export function t(key, fallback = '') {
  const currentLang = getAppLanguage();
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || fallback || key;
}

// React hook for seamless reactive localization
export function useTranslation() {
  const [lang, setLang] = useState(() => getAppLanguage());

  useEffect(() => {
    const active = SUPPORTED_LANGUAGES.find(l => l.code === lang) || SUPPORTED_LANGUAGES[0];
    document.documentElement.setAttribute('dir', active.dir);
    document.documentElement.setAttribute('lang', active.code);

    const handleLang = (e) => {
      setLang(e.detail?.language || getAppLanguage());
    };
    window.addEventListener('languageChange', handleLang);
    return () => window.removeEventListener('languageChange', handleLang);
  }, [lang]);

  const translate = (key, fallback = '') => {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
    return dict[key] || TRANSLATIONS.en[key] || fallback || key;
  };

  return {
    t: translate,
    currentLang: lang,
    setLanguage: setAppLanguage,
    languages: SUPPORTED_LANGUAGES,
    isRtl: (SUPPORTED_LANGUAGES.find(l => l.code === lang)?.dir) === 'rtl',
  };
}
